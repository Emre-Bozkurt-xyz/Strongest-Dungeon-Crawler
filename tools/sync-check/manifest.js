// Disk half of the sync check. Usage: node manifest.js [generate|clean|list]
// Writes src/server/dev/SyncManifest_<nonce>.luau mapping DataModel path -> "<fnv1a32 hex>:<byte length>"
// for every Rojo-mapped script file. The hash is FNV-1a 32 over the UTF-8 bytes after CRLF -> LF.
"use strict";
const fs = require("fs");
const path = require("path");
const http = require("http");

const REPO = path.resolve(__dirname, "..", "..");
const MANIFEST_DIR = path.join(REPO, "src", "server", "dev");
const MANIFEST_RE = /^SyncManifest_[0-9a-f]+\.luau$/;

// Mirrors default.project.json; the project file is read so a changed mapping is picked up.
function roots() {
	const proj = JSON.parse(fs.readFileSync(path.join(REPO, "default.project.json"), "utf8"));
	const out = [];
	const walk = (node, p) => {
		for (const [k, v] of Object.entries(node)) {
			if (k.startsWith("$") || typeof v !== "object") continue;
			if (v.$path) out.push({ dir: v.$path, dm: [...p, k] });
			else walk(v, [...p, k]);
		}
	};
	walk(proj.tree, []);
	return out;
}
// Vendored, never edited, not checked.
const SKIPPED_ROOTS = ["Packages", "ServerPackages"];

function hash(buf) {
	let h = 0x811c9dc5;
	for (let i = 0; i < buf.length; i++) {
		h ^= buf[i];
		h = (Math.imul(h, 0x01000193)) >>> 0;
	}
	return h.toString(16).padStart(8, "0") + ":" + buf.length;
}
function norm(buf) {
	// CRLF -> LF at the byte level (identical to a string replace for UTF-8).
	if (!buf.includes(13)) return buf;
	const out = Buffer.alloc(buf.length);
	let n = 0;
	for (let i = 0; i < buf.length; i++) {
		if (buf[i] === 13 && buf[i + 1] === 10) continue;
		out[n++] = buf[i];
	}
	return out.subarray(0, n);
}

const SCRIPT_RE = /^(.*?)(\.server|\.client)?\.(luau|lua)$/;

function scan(dir, dmPath, entries, skipped, stats) {
	for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, ent.name);
		if (ent.isDirectory()) {
			scan(full, [...dmPath, ent.name], entries, skipped, stats);
			continue;
		}
		const m = SCRIPT_RE.exec(ent.name);
		if (!m) {
			const ext = path.extname(ent.name) || ent.name;
			skipped[ext] = (skipped[ext] || 0) + 1;
			continue;
		}
		if (MANIFEST_RE.test(ent.name)) { stats.manifests++; continue; }
		const kind = m[2] ? m[2].slice(1) : "module";
		const isInit = m[1] === "init";
		const p = (isInit ? dmPath : [...dmPath, m[1]]).join(".");
		if (entries[p]) throw new Error("duplicate DataModel path " + p + " (" + full + ")");
		entries[p] = hash(norm(fs.readFileSync(full)));
		stats[kind] = (stats[kind] || 0) + 1;
		if (isInit) stats.init = (stats.init || 0) + 1;
	}
}

function listManifests() {
	return fs.readdirSync(MANIFEST_DIR).filter((f) => MANIFEST_RE.test(f)).map((f) => path.join(MANIFEST_DIR, f));
}

function generate() {
	const t0 = Date.now();
	const entries = {}, skipped = {}, stats = { manifests: 0 };
	for (const r of roots()) {
		if (SKIPPED_ROOTS.includes(r.dir)) continue;
		scan(path.join(REPO, r.dir), r.dm, entries, skipped, stats);
	}
	const keys = Object.keys(entries).sort();
	const nonce = Date.now().toString(16) + Math.floor(Math.random() * 0xffff).toString(16);
	const file = path.join(MANIFEST_DIR, `SyncManifest_${nonce}.luau`);
	let src = "--!nocheck\n-- Generated by tools/sync-check; never commit. Deleted by `run.ps1 clean`.\nreturn {\n";
	src += `\tgeneratedAt = ${Math.floor(Date.now() / 1000)},\n\tentries = {\n`;
	for (const k of keys) src += `\t\t["${k}"] = "${entries[k]}",\n`;
	src += "\t},\n}\n";
	fs.writeFileSync(file, src);
	console.log(`manifest: ${path.relative(REPO, file)}`);
	console.log(`scripts hashed: ${keys.length} (module ${stats.module || 0}, server ${stats.server || 0}, client ${stats.client || 0}; ${stats.init || 0} of them init files that become their folder)`);
	console.log(`older manifest files ignored in the scan: ${stats.manifests}`);
	console.log(`skipped file kinds (not scripts): ${JSON.stringify(skipped)}`);
	console.log(`not checked (vendored): ${SKIPPED_ROOTS.join(", ")}`);
	console.log(`disk side took ${Date.now() - t0} ms`);
	return nonce;
}

function clean() {
	const files = listManifests();
	for (const f of files) fs.unlinkSync(f);
	console.log(`removed ${files.length} manifest file(s)`);
}

function rojoStatus() {
	return new Promise((resolve) => {
		const req = http.get({ host: "localhost", port: 34872, path: "/api/rojo", timeout: 1500 }, (res) => {
			res.resume();
			resolve(res.statusCode === 200);
		});
		req.on("error", () => resolve(false));
		req.on("timeout", () => { req.destroy(); resolve(false); });
	});
}

const mode = process.argv[2] || "generate";
if (mode === "generate") generate();
else if (mode === "clean") clean();
else if (mode === "list") listManifests().forEach((f) => console.log(f));
else if (mode === "rojo") rojoStatus().then((ok) => console.log(ok ? "up" : "down"));
else { console.error("usage: node manifest.js [generate|clean|list|rojo]"); process.exit(2); }
